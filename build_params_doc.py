OUT = os.path.join(HERE, "docs", "ПАРАМЕТРИ_розрахунку_порогів.docx")


def f0(v):
    return "" if pd.isna(v) else f"{float(v):.0f}"


def f2(v):
    return "" if pd.isna(v) else f"{float(v):.2f}".replace(".", ",")


def fa(v):
    return "" if pd.isna(v) else f"{float(v):g}".replace(".", ",")


def pct(v):
    return "" if pd.isna(v) else f"{100 * float(v):.0f}%"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


conf = dict(zip(X["Конфігурація"]["параметр"], X["Конфігурація"]["значення"].astype(str)))
