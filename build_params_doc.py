import json
import os

import pandas as pd

from build_paper import convert

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(HERE, "config.json"), encoding="utf-8"))
X = pd.read_excel(os.path.join(HERE, "output", os.environ.get("MO_RESULTS", "memopt_results.xlsx")), sheet_name=None)
