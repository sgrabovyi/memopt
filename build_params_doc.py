lines.append(f"Для області, п'яти районів, п'яти районів без центру і п'яти міст (16 основних територій) набір сезонів програма добирає окремо для кожної території: "
             f"порівнює набори з усіх сезонів нинішнього періоду (з {CFG['season_selection']['era_start']}) і з доданими до них старшими сезонами і бере той, що дає найменшу сумарну помилку на контрольних сезонах. "
             f"Обрані набори мають від {min(nsets)} до {max(nsets)} сезонів, разом у них трапляються сезони {', '.join(main_seasons)}; набір кожної території показано в колонці «Сезони в розрахунку» на аркуші «Пороги».")
lines.append("")
lines.append(f"Усі 51 громада розраховані на {len(small_seasons)} сезонах: {', '.join(small_seasons)}, бо дані по громадах є лише з сезону {small_seasons[0]}. "
             f"Пороги громад будуються на власних даних громад за ці сезони, а пороги району-еталона для часткового об'єднання і для правила підтвердження районом беруться з розрахунку основних територій.")
