             f"Для кожного кута і кожного набору сезонів поріг перевіряли на контрольних сезонах (сезони нинішнього періоду, крім {', '.join(CFG['season_selection']['not_validation'])}): контрольний сезон відкладали, поріг будували за рештою сезонів набору і порівнювали з межами епідемії, "
             f"визначеними за даними самого сезону функцією memtiming пакета mem при стандартному куті {fa(ang['truth_angle'])}. Сезон, пік якого нижчий за епідемічний поріг, побудований тим самим кутом за іншими сезонами території, вважається сезоном без епідемії, і в ньому рахуються лише хибні сигнали. Критерій вибору: найменша сумарна помилка, тобто сума хибних сигналів і тижнів запізнення "
