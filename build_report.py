def signed(v, d=1):
    # відсоток зі словом замість знака: «мінус 10,2%», «плюс 6,3%»
    if np.isclose(v, 0):
        return "0%"
    return ("мінус " if v < 0 else "плюс ") + fm(abs(v), d) + "%"


