def c2(v):
    return ("%.2f" % v).replace(".", ",")


def fm(v, d=0):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "н/д"
    return (("%." + str(d) + "f") % v).replace(".", ",")


def table(df, rename=None, fmts=None):
    rename = rename or {}
    fmts = fmts or {}
    head = [rename.get(c, c) for c in df.columns]
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in df.columns:
            v = r[c]
            if c in fmts:
                cells.append(fmts[c](v))
            elif isinstance(v, (float, np.floating)):
                cells.append(fm(v, 1))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


