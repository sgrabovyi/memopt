def level(v, t):
    if v != v:
        return None
    return 4 if v >= t[3] else 3 if v >= t[2] else 2 if v >= t[1] else 1 if v >= t[0] else 0


def fm(v, d=0):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "н/д"
    return (("%." + str(d) + "f") % v).replace(".", ",")


def tbl(rows, head):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def window(rr, rb):
    """Період епідемії району: безперервна епізод тижнів, коли район не нижче свого базового (епідемічного) порогу, навколо його піка."""
    v = rr.values
    ok = [(x == x and x >= rb) for x in v]
    if not any(ok):
        return None
    pk = int(np.nanargmax(v))
    s = pk
    while s > 0 and (ok[s - 1] or (s > 1 and ok[s - 2] and v[s - 1] != v[s - 1])):
        s -= 1
    e = pk
    while e + 1 < len(v) and (ok[e + 1] or (e + 2 < len(v) and ok[e + 2] and v[e + 1] != v[e + 1])):
        e += 1
    return s, e


def prep(hid, S):
    r = terr[terr.id == hid].iloc[0]
    y = hrom(hid, S)
    rr_raw, rr = ref_series(r.reference_id, S)
    t = [SM.loc[hid, c] for c in COLS]
    rb = THR.loc[r.reference_id, "Епідемічний поріг"]
    lv = [level(v, t) for v in y.values]
    gate = np.array([(v >= rb) if v == v else False for v in rr.values])
    return r, y, rr_raw, rr, t, rb, lv, gate


def shown(lv, gate):
    return [None if l is None else (l if (l < 2 or g) else 1) for l, g in zip(lv, gate)]


def season_table(hid, S):
    r, y, rr_raw, rr, t, rb, lv, gate = prep(hid, S)
    sh = shown(lv, gate)
    pop = SM.loc[hid, "Населення"]
    rows = []
    for w, a, b, braw, l, g, s in zip(WEEKS, y.values, rr.values, rr_raw.values, lv, gate, sh):
        if l is None:
            continue
        rows.append([w, fm(a), fm(a * pop / 1e5), LV[l], fm(b) + ("*" if braw != braw else ""), "так" if g else "ні", LV[s] + ("*" if (s == 1 and l >= 2) else "")])
    return rows, t, rb, lv, sh


