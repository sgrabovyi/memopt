def evaluate():
    rows, runs_all = [], []
    for S in SEAS_EVAL:
        for hid in SMALL:
            r, y, rr_raw, rr, t, rb, lv, gate = prep(hid, S)
            w = window(rr, rb)
            if w is None:
                continue
            ws, we = w
            U = np.array([(l is not None and l >= 2) for l in lv])
            Gt = np.array([U[i] and gate[i] for i in range(len(U))])
            size = SM.loc[hid, "Медіана випадків на тиждень"]
            grp = "до 6" if size < 6 else "6-13" if size < 14 else "14-29" if size < 30 else "30 і більше"
            for name, a in (("без правила", U), ("правило", Gt)):
                rows.append(dict(season=S, id=hid, grp=grp, variant=name, inw=int(sum(1 for i in range(len(a)) if a[i] and ws <= i <= we)),
                                 outw=int(sum(1 for i in range(len(a)) if a[i] and not (ws <= i <= we)))))
            idx = [i for i in range(len(U)) if U[i]]
            runs = []
            for i in idx:
                if runs and i - runs[-1][-1] <= 2:
                    runs[-1].append(i)
                else:
                    runs.append([i])
            for run in runs:
                if not any(ws <= i <= we for i in run):
                    runs_all.append(dict(season=S, id=hid, grp=grp, touches=False, length=len(run), high=any((lv[i] or 0) >= 3 for i in run)))
                    continue
                f = [i for i in run if Gt[i]]
                runs_all.append(dict(season=S, id=hid, grp=grp, touches=True, length=len(run), high=any((lv[i] or 0) >= 3 for i in run),
                                     lag_own=(f[0] - run[0]), after_district=(f[0] - ws)))
    return pd.DataFrame(rows), pd.DataFrame(runs_all)


