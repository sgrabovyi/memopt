def k_loso(hid, S):
    num = den = 0
    for s2 in SEAS:
        if s2 == S:
            continue
        h, rr = HH[(hid, s2)], RR2[(hid, s2)]
        ok = ~np.isnan(h) & ~np.isnan(rr)
        num += h[ok].sum()
        den += rr[ok].sum()
    return num / den


