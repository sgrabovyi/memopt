def min_cases(N, mode):
    inw = outw = det = n = 0
    for S in SEAS_EVAL:
        for hid in SMALL:
            r, y, rr_raw, rr, t, rb, lv, gate = prep(hid, S)
            w = window(rr, rb)
            if w is None:
                continue
            ws, we = w
            U = np.array([(l is not None and l >= 2) for l in lv])
            cases = (y * POP[hid] / 1e5).values
            if mode == "2":
                cases = pd.Series(cases).rolling(2, min_periods=1).sum().values
            ok = np.array([(c == c and c >= N) for c in cases]) if N > 0 else np.ones(len(U), bool)
            a = np.array([U[i] and gate[i] and ok[i] for i in range(len(U))])
            n += 1
            i_in = [i for i in range(len(a)) if a[i] and ws <= i <= we]
            inw += len(i_in)
            outw += sum(1 for i in range(len(a)) if a[i] and not (ws <= i <= we))
            det += int(len(i_in) > 0)
    return [inw, outw, det, n]


